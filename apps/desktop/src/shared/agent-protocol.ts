// Versioned contract between Home (untrusted renderer), main and the agent
// host. Renderer requests never carry authority: no paths, no grants, no
// credentials, no approval digests. Main resolves folder grants and sends
// credentials to the host only on request.

export const AGENT_PROTOCOL_VERSION = 1

export const RUN_MODES = ['web', 'local'] as const
export type RunMode = typeof RUN_MODES[number]

export const RUN_STATUSES = ['queued', 'running', 'waiting_approval', 'waiting_user', 'succeeded', 'failed', 'cancelled', 'interrupted'] as const
export type RunStatus = typeof RUN_STATUSES[number]
export const TERMINAL_STATUSES: readonly RunStatus[] = ['succeeded', 'failed', 'cancelled', 'interrupted']
export const isTerminal = (status: RunStatus): boolean => TERMINAL_STATUSES.includes(status)

/** `temporary` runs keep everything in memory: history off or retention 0. */
export type Persistence = 'retained' | 'temporary'

export interface RunBudget {
  maxSteps: number
  maxOutputTokens: number
  maxWallMs: number
  /** Total bytes of tool output fed back to the model across the run. */
  maxToolOutputBytes: number
}
export const DEFAULT_BUDGET: RunBudget = { maxSteps: 24, maxOutputTokens: 60_000, maxWallMs: 15 * 60_000, maxToolOutputBytes: 2_000_000 }

export const ERROR_CODES = ['budget', 'provider', 'tool', 'policy', 'cancelled', 'host', 'model_unsupported', 'internal'] as const
export type AgentErrorCode = typeof ERROR_CODES[number]
export interface AgentError { code: AgentErrorCode; message: string }

export interface RunUsage { inputTokens: number; outputTokens: number }

export interface RunSummary {
  id: string
  conversationId?: string
  goal: string
  mode: RunMode
  /** True once the owner allowed both web and local tools in this run. */
  mixed: boolean
  status: RunStatus
  persistence: Persistence
  created: number
  updated: number
  usage: RunUsage
  error?: AgentError
}

export type AgentEventPayload =
  | { type: 'run.created'; goal: string; mode: RunMode; persistence: Persistence; budget: RunBudget }
  | { type: 'status'; status: RunStatus; reason?: string }
  /** Final model text for a step. Live token text travels as a transient `partial` push and is never persisted. */
  | { type: 'text'; step: number; text: string }
  | { type: 'tool.call'; step: number; callId: string; tool: string; input: string }
  | { type: 'tool.result'; callId: string; ok: boolean; summary: string; artifactId?: string }
  | { type: 'tool.denied'; callId: string; reason: string }
  /** `preview` is generated by trusted host code from normalized input, never by the model or a tool. */
  | { type: 'approval.requested'; approvalId: string; callId: string; tool: string; preview: string; digest: string }
  | { type: 'approval.decided'; approvalId: string; decision: 'approved' | 'denied' }
  | { type: 'question'; questionId: string; text: string }
  | { type: 'answer'; questionId: string; text: string }
  | { type: 'artifact'; artifactId: string; name: string; mediaType: string; bytes: number }
  | { type: 'mode.mixed'; allowed: RunMode }
  | { type: 'usage'; inputTokens: number; outputTokens: number }
  | { type: 'error'; code: AgentErrorCode; message: string }

export type AgentEventType = AgentEventPayload['type']

export interface AgentEvent { runId: string; seq: number; id: string; at: number; payload: AgentEventPayload }

/** Home → main. Every field is validated by `parseAgentRequest`. */
export type AgentRequest =
  | { kind: 'start'; requestId: string; goal: string; mode: RunMode; conversationId?: string; grantIds?: string[] }
  | { kind: 'approve'; runId: string; approvalId: string; decision: 'approved' | 'denied' }
  | { kind: 'answer'; runId: string; questionId: string; text: string }
  | { kind: 'allowMix'; runId: string }
  | { kind: 'cancel'; runId: string }
  | { kind: 'continue'; runId: string }
  | { kind: 'delete'; runId: string }
  | { kind: 'stopAll' }
  | { kind: 'list'; before?: number; limit: number }
  | { kind: 'events'; runId: string; afterSeq: number; limit: number }
  | { kind: 'artifact'; runId: string; artifactId: string }
  /** Main shows a native folder picker and returns an opaque grant ID. */
  | { kind: 'pickFolder' }

/** Results of `AgentApi.request`, by request kind. Main forwards host results unchanged. */
export interface AgentResults {
  start: { runId: string }
  list: { runs: RunSummary[] }
  events: { events: AgentEvent[] }
  /** Only text media types are previewable; content is capped at 1 MB. */
  artifact: { name: string; mediaType: string; bytes: number; text: string }
  pickFolder: { grant: { id: string; label: string } } | { cancelled: true }
  approve: { ok: true }; answer: { ok: true }; allowMix: { ok: true }; cancel: { ok: true }; continue: { ok: true }; delete: { ok: true }; stopAll: { ok: true }
}

/** Folder access resolved by main from a native picker; only main and host see paths. */
export interface FolderGrant { id: string; root: string; label: string }

/** Main → host. */
export type HostCommand =
  | { kind: 'start'; requestId: string; goal: string; mode: RunMode; persistence: Persistence; conversationId?: string; grants: FolderGrant[]; budget: RunBudget; model: ModelSelection; search?: SearchConfig }
  | { kind: 'approve'; runId: string; approvalId: string; decision: 'approved' | 'denied' }
  | { kind: 'answer'; runId: string; questionId: string; text: string }
  | { kind: 'allowMix'; runId: string }
  | { kind: 'cancel'; runId: string }
  /** Grants are the ones persisted with the run; main cannot widen them on continue. */
  | { kind: 'continue'; runId: string; model: ModelSelection }
  | { kind: 'delete'; runId: string }
  | { kind: 'deleteConversation'; conversationId: string }
  | { kind: 'cancelAll' }
  | { kind: 'list'; before?: number; limit: number }
  | { kind: 'events'; runId: string; afterSeq: number; limit: number }
  | { kind: 'artifact'; runId: string; artifactId: string }

/** Web search backend. Secrets (e.g. a Brave key) are fetched through `credential.request`, never sent here. */
export type SearchConfig = { provider: 'searxng'; baseURL: string } | { provider: 'brave' }

/** Which configured provider/model the host should use; the secret is fetched separately. */
export interface ModelSelection { provider: string; model: string; effort?: 'low' | 'medium' | 'high'; baseURL?: string }

/** Agent host lifecycle as seen by main and Home. `idle` = never started (lazy). */
export type HostState = 'idle' | 'starting' | 'ready' | 'crashed' | 'stopped'

/** Main → Home pushes on `AgentChannels.events`. */
export type AgentPush =
  | { kind: 'events'; events: AgentEvent[]; runs: RunSummary[] }
  /** Transient streaming text for the current step; replaced by the persisted `text` event. */
  | { kind: 'partial'; runId: string; step: number; text: string }
  | { kind: 'host'; state: HostState; message?: string }

export const AgentChannels = { request: 'heynimbo:agent-request', push: 'heynimbo:agent-push' } as const

/** Shape exposed by the Home preload as `window.heynimboApp.agent`. */
export interface AgentApi {
  request(request: AgentRequest): Promise<unknown>
  onPush(listener: (push: AgentPush) => void): () => void
}

/** Envelope on the main ↔ host MessagePort. */
export type MainToHost =
  | { v: 1; kind: 'init'; dataDir: string }
  | { v: 1; kind: 'command'; id: number; command: HostCommand }
  | { v: 1; kind: 'credential'; id: number; ok: true; secret: string } | { v: 1; kind: 'credential'; id: number; ok: false; message: string }

export type HostToMain =
  | { v: 1; kind: 'ready' }
  | { v: 1; kind: 'reply'; id: number; ok: true; result: unknown } | { v: 1; kind: 'reply'; id: number; ok: false; message: string }
  | { v: 1; kind: 'events'; events: AgentEvent[]; runs: RunSummary[] }
  | { v: 1; kind: 'partial'; runId: string; step: number; text: string }
  /** `name` is a provider ID or 'brave-search'. Main answers only for the run's configured provider. */
  | { v: 1; kind: 'credential.request'; id: number; name: string }

// ---------------------------------------------------------------------------
// Validation. Strict: unknown fields, wrong types and oversized values throw.

export const LIMITS = { goal: 16_000, answer: 16_000, id: 200, grants: 8, pageSize: 200, event: 64_000 } as const

function record(value: unknown, what: string): Record<string, unknown> {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error(`Invalid ${what}.`)
  return value as Record<string, unknown>
}
function only(input: Record<string, unknown>, keys: readonly string[], what: string): void {
  for (const key of Object.keys(input)) if (!keys.includes(key)) throw new Error(`Unknown ${what} field: ${key}.`)
}
function text(value: unknown, max: number, what: string, nonempty = true): string {
  if (typeof value !== 'string' || value.length > max || (nonempty && !value.trim())) throw new Error(`Invalid ${what}.`)
  return value
}
const ID = /^[A-Za-z0-9_-]{1,200}$/
function id(value: unknown, what: string): string {
  if (typeof value !== 'string' || !ID.test(value)) throw new Error(`Invalid ${what}.`)
  return value
}
function int(value: unknown, min: number, max: number, what: string): number {
  if (typeof value !== 'number' || !Number.isInteger(value) || value < min || value > max) throw new Error(`Invalid ${what}.`)
  return value
}
function oneOf<T extends string>(value: unknown, options: readonly T[], what: string): T {
  if (typeof value !== 'string' || !options.includes(value as T)) throw new Error(`Invalid ${what}.`)
  return value as T
}

export function parseAgentRequest(value: unknown): AgentRequest {
  const input = record(value, 'agent request')
  const k = input.kind
  switch (k) {
    case 'start': {
      only(input, ['kind', 'requestId', 'goal', 'mode', 'conversationId', 'grantIds'], 'start')
      const grantIds = input.grantIds === undefined ? undefined : (() => {
        if (!Array.isArray(input.grantIds) || input.grantIds.length > LIMITS.grants) throw new Error('Invalid folder grants.')
        return [...new Set(input.grantIds.map(g => id(g, 'folder grant')))]
      })()
      const mode = oneOf(input.mode, RUN_MODES, 'run mode')
      if (mode === 'web' && grantIds?.length) throw new Error('Web runs cannot include folder grants.')
      return { kind: 'start', requestId: id(input.requestId, 'request ID'), goal: text(input.goal, LIMITS.goal, 'goal'), mode, ...(input.conversationId !== undefined ? { conversationId: id(input.conversationId, 'conversation ID') } : {}), ...(grantIds ? { grantIds } : {}) }
    }
    case 'approve':
      only(input, ['kind', 'runId', 'approvalId', 'decision'], 'approve')
      return { kind: 'approve', runId: id(input.runId, 'run ID'), approvalId: id(input.approvalId, 'approval ID'), decision: oneOf(input.decision, ['approved', 'denied'] as const, 'decision') }
    case 'answer':
      only(input, ['kind', 'runId', 'questionId', 'text'], 'answer')
      return { kind: 'answer', runId: id(input.runId, 'run ID'), questionId: id(input.questionId, 'question ID'), text: text(input.text, LIMITS.answer, 'answer') }
    case 'allowMix': case 'cancel': case 'continue': case 'delete':
      only(input, ['kind', 'runId'], k)
      return { kind: k, runId: id(input.runId, 'run ID') }
    case 'stopAll': case 'pickFolder':
      only(input, ['kind'], k)
      return { kind: k }
    case 'list':
      only(input, ['kind', 'before', 'limit'], 'list')
      return { kind: 'list', limit: int(input.limit, 1, LIMITS.pageSize, 'page size'), ...(input.before !== undefined ? { before: int(input.before, 0, Number.MAX_SAFE_INTEGER, 'cursor') } : {}) }
    case 'events':
      only(input, ['kind', 'runId', 'afterSeq', 'limit'], 'events')
      return { kind: 'events', runId: id(input.runId, 'run ID'), afterSeq: int(input.afterSeq, 0, Number.MAX_SAFE_INTEGER, 'sequence'), limit: int(input.limit, 1, LIMITS.pageSize, 'page size') }
    case 'artifact':
      only(input, ['kind', 'runId', 'artifactId'], 'artifact')
      return { kind: 'artifact', runId: id(input.runId, 'run ID'), artifactId: id(input.artifactId, 'artifact ID') }
    default: throw new Error('Unknown agent request.')
  }
}

const EVENT_TYPES: readonly AgentEventType[] = ['run.created', 'status', 'text', 'tool.call', 'tool.result', 'tool.denied', 'approval.requested', 'approval.decided', 'question', 'answer', 'artifact', 'mode.mixed', 'usage', 'error']

/** Validates one event from the host before main forwards it to Home. */
export function parseAgentEvent(value: unknown): AgentEvent {
  const e = record(value, 'agent event')
  only(e, ['runId', 'seq', 'id', 'at', 'payload'], 'event')
  const p = record(e.payload, 'event payload')
  const type = oneOf(p.type, EVENT_TYPES, 'event type')
  if (JSON.stringify(p).length > LIMITS.event) throw new Error('Agent event too large.')
  const s = (key: string, max: number = LIMITS.event, nonempty = false): void => { text(p[key], max, `${type}.${key}`, nonempty) }
  const keys: Record<AgentEventType, readonly string[]> = {
    'run.created': ['goal', 'mode', 'persistence', 'budget'], status: ['status', 'reason'], text: ['step', 'text'],
    'tool.call': ['step', 'callId', 'tool', 'input'], 'tool.result': ['callId', 'ok', 'summary', 'artifactId'], 'tool.denied': ['callId', 'reason'],
    'approval.requested': ['approvalId', 'callId', 'tool', 'preview', 'digest'], 'approval.decided': ['approvalId', 'decision'],
    question: ['questionId', 'text'], answer: ['questionId', 'text'], artifact: ['artifactId', 'name', 'mediaType', 'bytes'],
    'mode.mixed': ['allowed'], usage: ['inputTokens', 'outputTokens'], error: ['code', 'message'],
  }
  only(p, ['type', ...keys[type]], type)
  switch (type) {
    case 'run.created': s('goal', LIMITS.goal, true); oneOf(p.mode, RUN_MODES, 'mode'); oneOf(p.persistence, ['retained', 'temporary'] as const, 'persistence'); record(p.budget, 'budget'); break
    case 'status': oneOf(p.status, RUN_STATUSES, 'status'); if (p.reason !== undefined) s('reason', 2000); break
    case 'text': int(p.step, 0, 10_000, 'step'); s('text'); break
    case 'tool.call': int(p.step, 0, 10_000, 'step'); id(p.callId, 'call ID'); s('tool', 100, true); s('input', 8000); break
    case 'tool.result': id(p.callId, 'call ID'); if (typeof p.ok !== 'boolean') throw new Error('Invalid tool result.'); s('summary', 8000); if (p.artifactId !== undefined) id(p.artifactId, 'artifact ID'); break
    case 'tool.denied': id(p.callId, 'call ID'); s('reason', 2000, true); break
    case 'approval.requested': id(p.approvalId, 'approval ID'); id(p.callId, 'call ID'); s('tool', 100, true); s('preview', 8000, true); s('digest', 128, true); break
    case 'approval.decided': id(p.approvalId, 'approval ID'); oneOf(p.decision, ['approved', 'denied'] as const, 'decision'); break
    case 'question': case 'answer': id(p.questionId, 'question ID'); s('text', LIMITS.answer, true); break
    case 'artifact': id(p.artifactId, 'artifact ID'); s('name', 300, true); s('mediaType', 200, true); int(p.bytes, 0, Number.MAX_SAFE_INTEGER, 'bytes'); break
    case 'mode.mixed': oneOf(p.allowed, RUN_MODES, 'mode'); break
    case 'usage': int(p.inputTokens, 0, Number.MAX_SAFE_INTEGER, 'tokens'); int(p.outputTokens, 0, Number.MAX_SAFE_INTEGER, 'tokens'); break
    case 'error': oneOf(p.code, ERROR_CODES, 'error code'); s('message', 2000, true); break
  }
  return { runId: id(e.runId, 'run ID'), seq: int(e.seq, 1, Number.MAX_SAFE_INTEGER, 'sequence'), id: id(e.id, 'event ID'), at: int(e.at, 0, Number.MAX_SAFE_INTEGER, 'timestamp'), payload: p as AgentEventPayload }
}

/** Derives the run persistence from the existing privacy settings. */
export function persistenceFor(settings: { saveHistory: boolean; retention: number | 'forever' }): Persistence {
  return !settings.saveHistory || settings.retention === 0 ? 'temporary' : 'retained'
}
